def calculate_gaussian_kernel(c_di, c_i, sigma):
    '''
    calculates the probability specified in step 4 of the SLDA paper.
    
    Parameters
    ----------
    c_di     :     tuple
        the (idx, x_coord, y_coord) of the document
    c_i      :     tuple
        the (idx, x_coord, y_coord) of the visual word/patch
    sigma    :     float
        the variance of the Gaussian kernel
        
    Returns
    -------
    Probability that word is assigned to document
    
    '''
    g_i, x_i, y_i = c_i
    g_di, x_di, y_di = c_di
    
    if g_i != g_di:
        d = 0
    else:
        d = 1
    
    return d * torch.exp(-((x_di - x_i)**2 + (y_di - y_i)**2)/(sigma**2))

def initialize_documents(all_shapes, n_docs, n_imgs):
    '''
    Choose document locations. 
    
    Parameters
    ----------
        all_shapes     :     array
            the dimensions of each image (height, width)
        n_docs     :      int
            the number of documents per image
        n_imgs     :    int
            the number of images 
    
    Returns
    -------
        c_d      :      array
            location of documents
        docs_in_img :   array
            a tensor n_imgs x n_docs that contains the document
            indices belonging to each image. 
    '''

    documents = []
    for img_id in range(0, all_shapes.shape[0]):
            for doc_id in range(0, n_docs):
                x_d = np.random.randint(0, all_shapes[img_id][1])
                y_d = np.random.randint(0, all_shapes[img_id][0])
                #documents[img_id][doc_id][1] = xd
                #documents[img_id][doc_id][0] = yd
                documents.append((img_id, x_d, y_d))
    c = torch.tensor(documents, dtype=int)

    total_docs = n_imgs * n_docs
    docs_in_img = torch.tensor([x for x in range(0, total_docs)], dtype=int).reshape((n_imgs,n_docs))

    return c, docs_in_img

def initialize_documents_spatialdata(c, n_docs, n_imgs):
    '''
    Choose document locations. 
    
    Parameters
    ----------
        all_shapes     :     array
            the dimensions of each image (height, width)
        n_docs     :      int
            the number of documents per image
        n_imgs     :    int
            the number of images 
    
    Returns
    -------
        c_d      :      array
            location of documents
        docs_in_img :   array
            a tensor n_imgs x n_docs that contains the document
            indices belonging to each image. 
    '''

    
    idx = np.random.choice(np.arange(0, c.shape[0]), size=n_docs, replace=False)
    c_d = torch.tensor(c[idx, :], dtype=int)

    total_docs = n_imgs * n_docs
    docs_in_img = torch.tensor([x for x in range(0, total_docs)], dtype=int).reshape((n_imgs,n_docs))

    return c_d, docs_in_img
                
def build_input_word_array(assignments, c):
    '''
    Builds the input data structure

    Parameters
    ----------
        assignments :   array/tensor
            the cluster assignments for each word. 
        c   :   array/tensor
            document coordinates and img id (img_id, x, y)
    
    Returns
    -------
        input array for model training
        
    '''
    assert c.shape[0] == assignments.shape[0]
    
    vec = []
    for i in range(0, c.shape[0]):
        vec.append((assignments[i], c[i][0], c[i][1], c[i][2]))
    return torch.tensor(vec, dtype=int)


def initialize_model(input_arr, n_imgs, n_docs, n_topics, vocab_size):
    '''
    Initializes the model. 

    Parameters
    ----------
        input_arr   :   tensor
            the input data structure, generated by
            build_input_word_array
        n_imgs  :   int
            the number of images in the training set
        n_docs  :   int
            the number of documents PER IMAGE, set by user
        n_topics    :   int
            the number of topics to assign documents to, set by user
        vocab_size  :   int
            the number of words in the vocabulary, set by user
    
    Returns
    -------
        z   :   tensor
             topic assignments
        docs    :   tensor
            document assignments
        n_dk    :   tensor
            per document, the number of times each topic 
            appears
        n_kw    :   tensor
            per topic, the number of times each
            word in the vocabulary appears
        n_d :   tensor
            a count of topics n each document
        n_k :   tensor
            a count of words in each topic
    '''
    total_docs = n_docs*n_imgs
    n_dk = torch.zeros((total_docs, n_topics), dtype=int) # per document, number of times topic, appears, changed from n_docs!
    n_kw = torch.zeros((n_topics, vocab_size), dtype=int) # per topic, number of times each word in vocab appears, 
    n_d = torch.zeros((total_docs,), dtype=int) # topics in each document, changed from n_docs!
    n_k = torch.zeros ((n_topics,), dtype=int) # words in each topic

    if torch.cuda.is_available():
        device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
        n_dk = n_dk.to(device)
        n_kw = n_kw.to(device)
        n_d = n_d.to(device)
        n_k = n_k.to(device)

    word = input_arr[:,0]
    d_dist = torch.distributions.Multinomial(probs=torch.ones(total_docs)/total_docs) #changed from n_docs!
    d_i = d_dist.sample(sample_shape=(word.shape[0],))
    docs = d_i.argmax(dim=1)
    _, n_d = torch.unique(docs, return_counts = True)

    z_dist = torch.distributions.Multinomial(probs=torch.ones(n_topics)/n_topics)
    z_i = z_dist.sample(sample_shape=(word.shape[0],))
    z = z_i.argmax(dim=1)
    _, n_k = torch.unique(z, return_counts = True)

    for i in range(0, word.shape[0]):
        n_dk[docs[i]][z[i]] += 1
        n_kw[z[i]][word[i]] += 1

    return z, docs, n_dk, n_kw, n_d, n_k    

def calculate_topic_conditional(alpha, beta, n_kw, n_dk, n_d,
                                n_k, word, d_i):
        left = (n_kw[:, word] + beta[word])/(n_k + torch.sum(beta))
        right = (n_dk[d_i] + alpha)/(n_d[d_i] + torch.sum(alpha))
        
        return left*right
    
def calculate_doc_conditional(d_i, z_i, n_dk, n_d, sigma, alpha,
                              g_d, g_i, x_d, y_d, x_i, y_i, docs_in_img):
    
    idx = docs_in_img[g_i]
    kernel_arg = torch.tensor(-1.0*((x_d-x_i)**2.0 + (y_d-y_i)**2)/sigma**2., dtype=float)
    gaussian = torch.exp(kernel_arg)
    right = (n_dk[idx, z_i] + alpha[z_i])/(n_d[d_i] + torch.sum(alpha))
    return gaussian*right
        
def estimate_pi(n_docs, n_topics, alpha, n_dk, n_d):
    return (n_dk + alpha)/(n_d + alpha.sum()).unsqueeze(-1)

def estimate_phi(n_topics, vocab_size, n_kw, n_k, beta):
    return (n_kw + beta)/(n_k + beta.sum()).unsqueeze(-1)

def make_vectorizable_vars(document_locs, input_arr, n_docs):
    g_i = input_arr[:,1].unique()
    gx = []
    gy = []
    for g in g_i:
        idx, = torch.where(document_locs[:,0] == g)
        gx.append(document_locs[idx, 1])
        gy.append(document_locs[idx, 2])

    all_g = input_arr[:,1]
    all_gx = torch.empty((len(all_g),n_docs))
    all_gy = torch.empty((len(all_g),n_docs))

    for i in range(0, len(all_g)):
        g = int(all_g[i])
        all_gx[i] = gx[g]
        all_gy[i] = gy[g]

    x_i = input_arr[:, 2]
    y_i = input_arr[:, 3]

    x_i_new = torch.empty((len(all_g), n_docs))
    y_i_new = torch.empty((len(all_g), n_docs))

    for i in range(0,n_docs):
        x_i_new[:, i] = x_i
        y_i_new[:, i] = y_i

    if torch.cuda.is_available():
        device = torch.device('cuda')
        x_i_new = x_i_new.to(device)
        y_i_new = y_i_new.to(device)
        all_gx = all_gx.to(device)
        all_gy = all_gy.to(device)

    return x_i_new, y_i_new, all_gx, all_gy

def train_model(input_arr, document_locs, docs_in_img, n_imgs, n_docs, n_topics, vocab_size,z, docs, n_dk, n_kw, n_d, n_k, alpha, beta, sigma, n_epochs, return_loss=False, verbose=False):

    if torch.cuda.is_available():
        device = torch.device('cuda')
        document_locs = document_locs.to(device)
        alpha = alpha.to(device)
        beta = beta.to(device)
        z = z.to(device)
        docs = docs.to(device)
        input_arr = input_arr.to(device)
    
    for epoch in range(0, n_epochs):
        #   perplexities = []
        if verbose:
            for i in trange(0, input_arr.shape[0]):

                # obtain info about the current visual word
                word = input_arr[i][0] # kmeans word assignment
                g_i = input_arr[i][1] # img assignment
                x_i = input_arr[i][2] # word x coord
                y_i = input_arr[i][3] # word y coord

                # get sampled doc and topic for this word
                d_i = int(docs[i])
                z_i = int(z[i])

                # everything except the current document and topic, 
                # for the conditional with gibbs 
                n_dk[d_i, z_i] -= 1
                n_kw[z_i, word] -= 1
                n_d[d_i] -= 1
                n_k[z_i] -= 1

                # get document coordinates for the selected image.
                idx,  = torch.where(document_locs[:,0] == g_i)
                #coord = document_locs[idx][d_i][1:] # yields tensor([x_d, y_d])

                # Now compute two conditionals for the chosen topic and doc 

                p_topics = calculate_topic_conditional(alpha, beta, n_kw, n_dk, 
                                                    n_d, n_k, word, d_i)

                x_d = document_locs[idx, 1]
                y_d = document_locs[idx, 2]
                
                p_docs = calculate_doc_conditional(d_i, z_i, n_dk, n_d, sigma, alpha, g_i, g_i,
                                                x_d, y_d, x_i, y_i, docs_in_img)

                # re-normalize
                p_topics = p_topics/torch.sum(p_topics)
                p_docs = p_docs/torch.sum(p_docs)
                
                #print(p_topics, p_docs)

                # sample new document and topic
                #new_topic = int(pyro.sample("new_topic", dist.Multinomial(probs=p_topics)).argmax())
                #new_doc = int(pyro.sample("new_doc", dist.Multinomial(probs=p_docs)).argmax())
                new_topic_multinomial = torch.distributions.multinomial.Multinomial(probs=p_topics)
                new_topic = int(new_topic_multinomial.sample().argmax())
                new_doc_dist = torch.distributions.multinomial.Multinomial(probs=p_docs)
                new_doc = int(new_doc_dist.sample().argmax()) 

                # update counts
                n_dk[new_doc, new_topic] += 1
                n_kw[new_topic, word] += 1
                n_d[new_doc] += 1
                n_k[new_topic] += 1

                # update assignments
                docs[i] = new_doc
                z[i] = new_topic
        else:
            for i in range(0, input_arr.shape[0]):

                # obtain info about the current visual word
                word = input_arr[i][0] # kmeans word assignment
                g_i = input_arr[i][1] # img assignment
                x_i = input_arr[i][2] # word x coord
                y_i = input_arr[i][3] # word y coord

                # get sampled doc and topic for this word
                d_i = int(docs[i])
                z_i = int(z[i])

                # everything except the current document and topic, 
                # for the conditional with gibbs 
                n_dk[d_i, z_i] -= 1
                n_kw[z_i, word] -= 1
                n_d[d_i] -= 1
                n_k[z_i] -= 1

                # get document coordinates for the selected image.
                idx,  = torch.where(document_locs[:,0] == g_i)
                #coord = document_locs[idx][d_i][1:] # yields tensor([x_d, y_d])

                # Now compute two conditionals for the chosen topic and doc 

                p_topics = calculate_topic_conditional(alpha, beta, n_kw, n_dk, 
                                                    n_d, n_k, word, d_i)

                x_d = document_locs[idx, 1]
                y_d = document_locs[idx, 2]
                
                p_docs = calculate_doc_conditional(d_i, z_i, n_dk, n_d, sigma, alpha, g_i, g_i,
                                                x_d, y_d, x_i, y_i, docs_in_img)

                # re-normalize
                p_topics = p_topics/torch.sum(p_topics)
                p_docs = p_docs/torch.sum(p_docs)
                
                #print(p_topics, p_docs)

                # sample new document and topic
                #new_topic = int(pyro.sample("new_topic", dist.Multinomial(probs=p_topics)).argmax())
                #new_doc = int(pyro.sample("new_doc", dist.Multinomial(probs=p_docs)).argmax())
                new_topic_multinomial = torch.distributions.multinomial.Multinomial(probs=p_topics)
                new_topic = int(new_topic_multinomial.sample().argmax())
                new_doc_dist = torch.distributions.multinomial.Multinomial(probs=p_docs)
                new_doc = int(new_doc_dist.sample().argmax()) 

                # update counts
                n_dk[new_doc, new_topic] += 1
                n_kw[new_topic, word] += 1
                n_d[new_doc] += 1
                n_k[new_topic] += 1

                # update assignments
                docs[i] = new_doc
                z[i] = new_topic

        # compute max likelihood parameters
        pi_hat = estimate_pi(n_docs, n_topics, alpha, n_dk, n_d)
        phi_hat = estimate_phi(n_topics, vocab_size, n_kw, n_k, beta)

        # Calculate the log-likelihood of data matching these params
        
        x_i_new, y_i_new, all_gx, all_gy = make_vectorizable_vars(document_locs, input_arr, n_docs)
        
        doc_probabilities = torch.mm(pi_hat, phi_hat)
        d_probs = torch.exp(-((x_i_new-all_gx)**2 + (y_i_new-all_gy)**2)/sigma**2)
        n_words_per_image = int(d_probs.shape[0]/n_imgs)
        d_probs_new = torch.zeros((d_probs.shape[0], n_docs*n_imgs))

        for g_i in range(0, n_imgs):
            first_word = g_i * n_words_per_image
            last_word = (g_i + 1) * n_words_per_image
            first_doc = g_i * n_docs
            last_doc = (g_i + 1) * n_docs
            
            d_probs_new[first_word:last_word, first_doc:last_doc] = d_probs[first_word:last_word, :]
        
        word_probabilities = torch.mm(d_probs_new, doc_probabilities)
        rowsum = torch.sum(word_probabilities, axis=1)
        normed_word_probabilities = torch.div(word_probabilities.T, rowsum).T
        indices = input_arr[:,0].reshape((normed_word_probabilities.shape[0],1))
        p = normed_word_probabilities.gather(1, indices).reshape(normed_word_probabilities.shape[0])
        loglikelihood = torch.sum(torch.log(p))
        perplexity = torch.exp(-loglikelihood/input_arr.shape[0]) #https://stats.stackexchange.com/questions/18167/how-to-calculate-perplexity-of-a-holdout-with-latent-dirichlet-allocation
        #perplexities.append(perplexity)
        print(epoch, perplexity.item())
    
    if return_loss:
        return pi_hat, phi_hat, n_dk, n_kw, n_k, n_d, docs, z, perplexity.item()
    else:
        return pi_hat, phi_hat, n_dk, n_kw, n_k, n_d, docs, z

def get_topic_assignments(phi_hat, pi_hat, document_locs, input_arr, n_docs, c, assignments, sigma, n_topics):
    '''
    Given the results of the training, assign each cell
    to a topic label.
    '''
    best_topics = torch.zeros((phi_hat.shape[1], pi_hat.shape[0], phi_hat.shape[0]))

    for w in range(phi_hat.shape[1]):
        for d in range(pi_hat.shape[0]):
            best_topics[w][d] = pi_hat[d]*phi_hat[:, w]

    best_topic = torch.zeros((len(c),))
    x_i_new, y_i_new, all_gx, all_gy = make_vectorizable_vars(document_locs, input_arr, n_docs)

    topic_probs = torch.zeros((best_topic.shape[0], n_topics))
    for i in range(0, best_topic.shape[0]):
        g = int(c[i, 0])
        x = c[i, 1]
        y = c[i, 2]
        word = assignments[i]
        start = g * n_docs
        end = (g+1) * n_docs
        p = best_topics[word, start:end, :].T @ torch.exp(-((x-document_locs[start:end, 1])**2 + (y-document_locs[start:end, 2])**2)/sigma**2)
        best_topic[i] = p.argmax()
        topic_probs[i, :] = p
        
    return topic_probs, best_topic

def run_slda(assignments, points, n_topics, vocab_size, n_docs, n_imgs, sigma, n_epochs):
    alpha = torch.ones((n_topics,))/n_topics
    beta = torch.ones(vocab_size)/vocab_size
    ids = np.zeros((points.shape[0],1))
    c = np.concatenate([ids, points], axis=1)
    input_arr = build_input_word_array(assignments, c)

    z, docs, n_dk, n_kw, n_d, n_k = initialize_model(input_arr, n_imgs, n_docs, n_topics, vocab_size)
    document_locs, docs_in_img = initialize_documents_spatialdata(c, n_docs, n_imgs)
    pi_hat, phi_hat, n_dk, n_kw, n_k, n_d, docs, z = train_model(input_arr, document_locs, docs_in_img, n_imgs,
                                                    n_docs, n_topics, vocab_size, z, docs, n_dk, 
                                                    n_kw, n_d, n_k, alpha, beta, sigma, n_epochs)

    best_topics = torch.zeros((phi_hat.shape[1], pi_hat.shape[0], phi_hat.shape[0]))

    for w in range(phi_hat.shape[1]):
        for d in range(pi_hat.shape[0]):
            best_topics[w][d] = pi_hat[d]*phi_hat[:, w]

    best_topic = torch.zeros((len(c),))
    x_i_new, y_i_new, all_gx, all_gy = make_vectorizable_vars(document_locs, input_arr, n_docs)

    topic_probs = torch.zeros((best_topic.shape[0], n_topics))
    for i in trange(0, best_topic.shape[0]):
        g = int(c[i, 0])
        x = c[i, 1]
        y = c[i, 2]
        word = assignments[i]
        start = g * n_docs
        end = (g+1) * n_docs
        p = best_topics[word, start:end, :].T @ torch.exp(-((x-document_locs[start:end, 1])**2 + (y-document_locs[start:end, 2])**2)/sigma**2)
        best_topic[i] = p.argmax()
        topic_probs[i, :] = p

    return best_topic, topic_probs

